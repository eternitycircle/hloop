// Completion reports are written by hloop, not by an agent, so they record
// what was checked rather than what an agent says happened.

// ReportPath is the report's path relative to .loop/.
func ReportPath(taskID string) string { return "reports/" + taskID + ".md" }

func cell(s string) string {
	s = strings.ReplaceAll(strings.TrimSpace(s), "\n", " ")
	s = strings.ReplaceAll(s, "|", "\\|")
	if s == "" {
		return "-"
	}
	return s
}

// RenderReport builds the completion report for one task.
func RenderReport(p store.Project, cfg store.Config, l store.Ledger, t store.Task) string {
	var b strings.Builder
	fmt.Fprintf(&b, "<!-- GENERATED by hloop. Regenerate with `hloop task report %s`. -->\n", t.ID)
	fmt.Fprintf(&b, "# Completion report: %s %s\n\n", t.ID, t.Title)
	fmt.Fprintf(&b, "| | |\n|---|---|\n")
	fmt.Fprintf(&b, "| Status | %s |\n| Kind | %s |\n", t.Status, t.EffKind())
	if t.Spec != "" {
		fmt.Fprintf(&b, "| Spec | .loop/%s |\n", t.Spec)
	}
	if t.Done != nil {
		fmt.Fprintf(&b, "| Finished | %s |\n", t.Done.Local().Format("2006-01-02 15:04"))
	}
	if t.StartCommit != "" || t.Commit != "" {
		fmt.Fprintf(&b, "| Commits | %s..%s |\n", orStr(short(t.StartCommit), "?"), orStr(short(t.Commit), "?"))
	}
	if t.RedCommit != "" {
		fmt.Fprintf(&b, "| Tests-only (red) commit | %s |\n", short(t.RedCommit))
	}
	fmt.Fprintf(&b, "| Rejected finishes | %d |\n", t.GateFails)
	if t.Summary != "" {
		fmt.Fprintf(&b, "\n**Builder's summary:** %s\n", strings.TrimSpace(t.Summary))
	}

	b.WriteString("\n## Acceptance criteria\n\n")
	if len(t.Criteria) == 0 {
		b.WriteString("_None recorded. Without criteria, \"done\" means only that the gates passed. Add them with `hloop task add --ac` or `hloop spec`._\n")
	} else {
		b.WriteString("| ID | Priority | Criterion | Verify by | Status | Evidence |\n|---|---|---|---|---|---|\n")
		for _, c := range t.Criteria {
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n", c.ID, c.Priority, cell(c.Text), cell(c.Verify), c.Status, cell(c.Evidence))
		}
	}

	b.WriteString("\n## Checked by hloop\n\n")
	if len(t.Checks) == 0 {
		b.WriteString("_No checks recorded._\n")
	} else {
		b.WriteString("| Check | Result | Detail |\n|---|---|---|\n")
		for _, c := range t.Checks {
			res := "pass"
			if !c.OK {
				res = "FAIL"
			}
			fmt.Fprintf(&b, "| %s | %s | %s |\n", cell(c.Name), res, cell(firstLineStr(c.Detail)))
		}
	}
	if len(cfg.Gates) == 0 {
		b.WriteString("\nNo gates are configured, so hloop accepted the finish on the agent's word. Add one: `hloop gate add test -- <your test command>`.\n")
	}

	b.WriteString("\n## Guardrail detectors\n\nRun by hloop after every turn of an agent that may change the project.\n\n")
	b.WriteString("| Detector | Configured action | Fired during this task |\n|---|---|---|\n")
	fired := map[string][]string{}
	for _, ev := range t.GuardEvents {
		fired[ev.Name] = append(fired[ev.Name], ev.Detail)
	}
	g := cfg.Guards
	for _, d := range []struct{ name, action string }{
		{"history_rewrite", g.HistoryRewrite}, {"protected_commit", g.ProtectedCommit},
		{"dependency_change", g.DependencyChange}, {"mass_delete", g.MassDelete},
	} {
		f := "no"
		if evs := fired[d.name]; len(evs) > 0 {
			f = fmt.Sprintf("yes (%d): %s", len(evs), evs[len(evs)-1])
		}
		fmt.Fprintf(&b, "| %s | %s | %s |\n", d.name, d.action, cell(f))
	}

	if IsGitRepo(p.Root) && t.StartCommit != "" {
		end := t.Commit
		if end == "" {
			end = "HEAD"
		}
		if log, err := gitOut(p.Root, "log", "--oneline", "-n", "30", t.StartCommit+".."+end); err == nil && log != "" {
			b.WriteString("\n## Commits\n\n```\n" + log + "\n```\n")
		}
		if stat, err := gitOut(p.Root, "diff", "--stat=100", t.StartCommit, end, "--", ".", ":(exclude)"+store.DirName); err == nil && stat != "" {
			lines := strings.Split(stat, "\n")
			if len(lines) > 40 {
				lines = append(lines[:39], fmt.Sprintf("... %d more lines", len(lines)-39))
			}
			b.WriteString("\n## Files changed\n\n```\n" + strings.Join(lines, "\n") + "\n```\n")
		}
	}

	if t.Done != nil {
		var next *time.Time
		for _, x := range l.Tasks {
			if x.Done != nil && x.Done.After(*t.Done) && (next == nil || x.Done.Before(*next)) {
				d := *x.Done
				next = &d
			}
		}
		var rs []store.Review
		for _, r := range l.Reviews {
			if !r.Time.Before(*t.Done) && (next == nil || r.Time.Before(*next)) {
				rs = append(rs, r)
			}
		}
		if len(rs) > 0 {
			b.WriteString("\n## Reviews\n\n")
			for _, r := range rs {
				fmt.Fprintf(&b, "- **%s** by %s: %s. %s\n", r.ID, r.Agent, r.Verdict, strings.TrimSpace(r.Summary))
			}
		}
	}
	return b.String()
}

func firstLineStr(s string) string {
	if i := strings.IndexByte(s, '\n'); i >= 0 {
		return s[:i]
	}
	return s
}

// WriteReport renders and saves the report for a task and records its path.
func WriteReport(p store.Project, cfg store.Config, taskID string) (string, error) {
	l, err := store.LoadLedger(p)
	if err != nil {
		return "", err
	}
	t := l.FindTask(taskID)
	if t == nil {
		return "", fmt.Errorf("no task %s", store.NormID("T", taskID))
	}
	rel := ReportPath(t.ID)
	if err := store.WriteFile(p.Path(filepath.FromSlash(rel)), []byte(RenderReport(p, cfg, l, *t)), 0o644); err != nil {
		return "", err
	}
	if t.Report != rel {
		_ = store.UpdateLedger(p, func(l *store.Ledger) error {
			if x := l.FindTask(taskID); x != nil {
				x.Report = rel
			}
			return nil
		})
	}
	return rel, nil
}
