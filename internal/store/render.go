const generatedBanner = "<!-- GENERATED by hloop from .loop/ledger.json. Do not edit by hand; use `hloop` commands (task, blocker, decision, note). -->\n"

func shortDate(t time.Time) string { return t.Format("2006-01-02") }

// RenderProgress builds the PROGRESS.md view.
func RenderProgress(name string, l Ledger) string {
	var b strings.Builder
	b.WriteString(generatedBanner)
	fmt.Fprintf(&b, "# Progress Ledger: %s\n\n", name)

	b.WriteString("## Blockers / User Action Required\n")
	open := l.OpenBlockers()
	if len(open) == 0 {
		b.WriteString("- Status: None\n")
	} else {
		b.WriteString("- Status: BLOCKED\n")
		for _, x := range open {
			fmt.Fprintf(&b, "- **%s** (opened %s): %s\n", x.ID, shortDate(x.Opened), x.Text)
		}
	}
	var answered []Blocker
	for _, x := range l.Blockers {
		if x.Resolved {
			answered = append(answered, x)
		}
	}
	if len(answered) > 0 {
		b.WriteString("\n### Recently answered by the human\n")
		start := len(answered) - 5
		if start < 0 {
			start = 0
		}
		for _, x := range answered[start:] {
			fmt.Fprintf(&b, "- **%s**: %s\n  - Answer: %s\n", x.ID, x.Text, x.Answer)
		}
	}

	b.WriteString("\n## Current Task\n")
	if c := l.Current(); c != nil {
		fmt.Fprintf(&b, "- [~] **%s** %s (IN_PROGRESS)\n", c.ID, c.Title)
		if c.Detail != "" {
			fmt.Fprintf(&b, "  - %s\n", strings.ReplaceAll(c.Detail, "\n", "\n    "))
		}
		if c.Spec != "" {
			fmt.Fprintf(&b, "  - Spec: .loop/%s\n", c.Spec)
		}
		b.WriteString(RenderCriteria(c.Criteria, "  "))
	} else {
		b.WriteString("- None\n")
	}

	b.WriteString("\n## Pending Task Queue\n")
	n := 0
	for _, t := range l.Tasks {
		if t.Status == TaskPending {
			fmt.Fprintf(&b, "- [ ] **%s** %s\n", t.ID, t.Title)
			n++
		}
	}
	if n == 0 {
		b.WriteString("- Empty\n")
	}
	var proposed []Task
	for _, t := range l.Tasks {
		if t.Status == TaskProposed {
			proposed = append(proposed, t)
		}
	}
	if len(proposed) > 0 {
		b.WriteString("\n## Proposed (awaiting human approval; do not work on these)\n")
		for _, t := range proposed {
			fmt.Fprintf(&b, "- [?] **%s** %s (from %s)\n", t.ID, t.Title, t.Source)
		}
	}

	b.WriteString("\n## Completed Tasks\n")
	var done []Task
	for _, t := range l.Tasks {
		if t.Status == TaskDone {
			done = append(done, t)
		}
	}
	if len(done) > progressDoneShown {
		fmt.Fprintf(&b, "- %d earlier finished task(s) not shown here; the complete history is in PROGRESS_LOG.md\n", len(done)-progressDoneShown)
		done = done[len(done)-progressDoneShown:]
	}
	n = 0
	for _, t := range done {
		line := fmt.Sprintf("- [x] **%s** %s", t.ID, t.Title)
		if t.Commit != "" {
			line += fmt.Sprintf(" (%s)", t.Commit)
		}
		b.WriteString(line + "\n")
		if t.Summary != "" {
			fmt.Fprintf(&b, "  - %s\n", strings.ReplaceAll(t.Summary, "\n", " "))
		}
		if t.Verified != "" {
			fmt.Fprintf(&b, "  - Verified by hloop: %s\n", t.Verified)
		}
		n++
	}
	if n == 0 {
		b.WriteString("- None yet\n")
	}

	if oi := l.OpenIdeas(); len(oi) > 0 {
		b.WriteString("\n## Ideas (parked; never worked on until a human promotes one)\n")
		for _, x := range oi {
			fmt.Fprintf(&b, "- %s %s\n", x.ID, x.Text)
		}
	}

	if len(l.Reviews) > 0 {
		b.WriteString("\n## Recent Reviews\n")
		start := len(l.Reviews) - 5
		if start < 0 {
			start = 0
		}
		for _, r := range l.Reviews[start:] {
			fmt.Fprintf(&b, "- **%s** %s by %s: %s\n  - %s\n", r.ID, shortDate(r.Time), r.Agent, r.Verdict, strings.ReplaceAll(r.Summary, "\n", " "))
		}
	}
	return b.String()
}

// progressDoneShown caps the completed list so PROGRESS.md (which agents read
// every turn) does not grow forever.
const progressDoneShown = 10

// RenderCriteria lists acceptance criteria as markdown lines with an indent.
func RenderCriteria(cs []Criterion, indent string) string {
	if len(cs) == 0 {
		return ""
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%s- Acceptance criteria:\n", indent)
	for _, c := range cs {
		mark := map[string]string{CritPass: "x", CritFail: "!", CritOpen: " "}[c.Status]
		if mark == "" {
			mark = " "
		}
		fmt.Fprintf(&b, "%s  - [%s] %s (%s) %s", indent, mark, c.ID, strings.ToUpper(c.Priority[:1])+c.Priority[1:], c.Text)
		if c.Verify != "" {
			fmt.Fprintf(&b, " _verify: %s_", c.Verify)
		}
		if c.Evidence != "" {
			fmt.Fprintf(&b, " (evidence: %s)", c.Evidence)
		}
		b.WriteString("\n")
	}
	return b.String()
}

// RenderProgressLog builds PROGRESS_LOG.md: the complete, never-trimmed
// history of the project (every finished task and every event the ledger
// records), for humans and for agents that need history.
func RenderProgressLog(name string, l Ledger) string {
	var b strings.Builder
	b.WriteString(generatedBanner)
	fmt.Fprintf(&b, "# Progress log: %s\n\nThe complete history of the loop, oldest first. Nothing is ever removed. PROGRESS.md shows only the current state and the latest finished tasks.\n\n", name)
	fmt.Fprintf(&b, "**Totals:** %d done, %d in progress, %d pending, %d skipped, %d awaiting approval. %d blocker(s) raised, %d review(s), %d decision(s) recorded.\n",
		l.Count(TaskDone), l.Count(TaskInProgress), l.Count(TaskPending), l.Count(TaskSkipped), l.Count(TaskProposed), len(l.Blockers), len(l.Reviews), len(l.Decisions))

	var done []Task
	for _, t := range l.Tasks {
		if t.Status == TaskDone {
			done = append(done, t)
		}
	}
	sort.SliceStable(done, func(i, j int) bool { return timeOf(done[i].Done).Before(timeOf(done[j].Done)) })
	b.WriteString("\n## Finished tasks\n\n")
	if len(done) == 0 {
		b.WriteString("_None yet._\n")
	} else {
		b.WriteString("| # | Task | Finished | Commit | Verified by hloop | Report |\n|---|---|---|---|---|---|\n")
		for i, t := range done {
			when := "-"
			if t.Done != nil {
				when = t.Done.Local().Format("2006-01-02 15:04")
			}
			rep := "-"
			if t.Report != "" {
				rep = "[" + t.ID + "](" + t.Report + ")"
			}
			fmt.Fprintf(&b, "| %d | **%s** %s | %s | %s | %s | %s |\n", i+1, t.ID, cellText(t.Title), when, orDash(t.Commit), cellText(orDash(t.Verified)), rep)
		}
	}
	if len(l.Releases) > 0 {
		b.WriteString("\n## Releases\n\n| Version | Date | Tasks | Release notes |\n|---|---|---|---|\n")
		for i := len(l.Releases) - 1; i >= 0; i-- {
			r := l.Releases[i]
			fmt.Fprintf(&b, "| v%s | %s | %s | %s |\n", r.Version, r.Date.Local().Format("2006-01-02"), cellText(orDash(strings.Join(r.Tasks, ", "))), r.Notes)
		}
	}
	var skipped []Task
	for _, t := range l.Tasks {
		if t.Status == TaskSkipped {
			skipped = append(skipped, t)
		}
	}
	if len(skipped) > 0 {
		b.WriteString("\n## Skipped tasks\n")
		for _, t := range skipped {
			fmt.Fprintf(&b, "- **%s** %s\n", t.ID, t.Title)
		}
	}

	type ev struct {
		at   time.Time
		text string
	}
	var evs []ev
	add := func(at time.Time, f string, a ...any) {
		if !at.IsZero() {
			evs = append(evs, ev{at, fmt.Sprintf(f, a...)})
		}
	}
	for _, t := range l.Tasks {
		add(t.Added, "%s queued: %s (from %s)", t.ID, t.Title, orDash(t.Source))
		for _, g := range t.GuardEvents {
			add(g.At, "guardrail %s during %s: %s", g.Name, t.ID, oneLineStr(g.Detail))
		}
		for _, c := range t.Rejections {
			add(c.At, "%s finish rejected by hloop: %s: %s", t.ID, c.Name, oneLineStr(c.Detail))
		}
		if t.Done != nil {
			line := fmt.Sprintf("%s finished: %s", t.ID, t.Title)
			if t.Commit != "" {
				line += " (" + t.Commit + ")"
			}
			if t.GateFails > 0 {
				line += fmt.Sprintf(" after %d rejected attempt(s)", t.GateFails)
			}
			if t.Summary != "" {
				line += ". " + oneLineStr(t.Summary)
			}
			add(*t.Done, "%s", line)
		}
	}
	for _, x := range l.Blockers {
		add(x.Opened, "%s raised by %s: %s", x.ID, orDash(x.Source), oneLineStr(x.Text))
		if x.ResolvedAt != nil {
			add(*x.ResolvedAt, "%s answered: %s", x.ID, oneLineStr(x.Answer))
		}
	}
	for _, r := range l.Reviews {
		add(r.Time, "%s review by %s: %s. %s", r.ID, r.Agent, r.Verdict, oneLineStr(r.Summary))
	}
	for _, x := range l.Ideas {
		add(x.Added, "%s idea parked: %s", x.ID, x.Text)
	}
	for _, x := range l.Lessons {
		add(x.Added, "%s lesson %s: %s", x.ID, x.Status, x.Text)
	}
	for _, r := range l.Releases {
		add(r.Date, "RELEASED v%s: %d task(s); notes in %s", r.Version, len(r.Tasks), r.Notes)
	}
	sort.SliceStable(evs, func(i, j int) bool { return evs[i].at.Before(evs[j].at) })
	b.WriteString("\n## Timeline\n")
	if len(evs) == 0 {
		b.WriteString("\n_Nothing has happened yet._\n")
	}
	day := ""
	for _, e := range evs {
		d := e.at.Local().Format("2006-01-02")
		if d != day {
			fmt.Fprintf(&b, "\n### %s\n", d)
			day = d
		}
		fmt.Fprintf(&b, "- %s %s\n", e.at.Local().Format("15:04"), e.text)
	}
	var decided []Decision
	for _, d := range l.Decisions {
		if d.Status == DecisionDecided {
			decided = append(decided, d)
		}
	}
	if len(decided) > 0 {
		b.WriteString("\n## Decisions made\n")
		for _, d := range decided {
			fmt.Fprintf(&b, "- %s %s: %s: %s\n", orDash(d.Date), d.ID, d.Topic, d.Decision)
		}
	}
	return b.String()
}

func timeOf(t *time.Time) time.Time {
	if t == nil {
		return time.Time{}
	}
	return *t
}

func cellText(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(strings.TrimSpace(s), "\n", " "), "|", "\\|")
}

func oneLineStr(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if len(s) > 240 {
		s = s[:237] + "..."
	}
	return s
}

// RenderSpecTasks builds specs/<feature>/tasks.md: the tasks that carry out
// one spec, generated from the ledger (the ledger stays the source of truth).
func RenderSpecTasks(spec string, l Ledger) string {
	var b strings.Builder
	b.WriteString(generatedBanner)
	fmt.Fprintf(&b, "# Tasks for %s\n\n", spec)
	n := 0
	for _, t := range l.Tasks {
		if t.Spec != spec {
			continue
		}
		n++
		mark := map[string]string{TaskPending: " ", TaskInProgress: "~", TaskDone: "x", TaskSkipped: "-", TaskProposed: "?"}[t.Status]
		fmt.Fprintf(&b, "- [%s] **%s** %s (%s)\n", mark, t.ID, t.Title, t.Status)
		b.WriteString(RenderCriteria(t.Criteria, "  "))
	}
	if n == 0 {
		b.WriteString("_No tasks reference this spec yet._\n")
	}
	return b.String()
}

// RenderLessons builds the LESSONS.md view.
func RenderLessons(l Ledger) string {
	var b strings.Builder
	b.WriteString(generatedBanner)
	b.WriteString("# Lessons learned\n\nShort, durable facts about working on this project, learned the hard way. Active lessons are given to every agent turn. Lessons proposed by an agent wait for a human (`hloop lesson approve <id>`).\n")
	for _, sec := range []struct{ st, title string }{{LessonActive, "Active"}, {LessonProposed, "Proposed (not used until approved)"}} {
		ls := l.LessonsWith(sec.st)
		if len(ls) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n## %s\n", sec.title)
		for _, x := range ls {
			fmt.Fprintf(&b, "- **%s** %s (from %s, %s)\n", x.ID, x.Text, orDash(x.Source), shortDate(x.Added))
		}
	}
	if len(l.Lessons) == 0 {
		b.WriteString("\n_No lessons yet._\n")
	}
	return b.String()
}

func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

// RenderDecisions builds the DECISIONS.md view.
func RenderDecisions(l Ledger) string {
	var b strings.Builder
	b.WriteString(generatedBanner)
	b.WriteString("# Decisions & Open Questions Log\n\n")
	b.WriteString("Status is `Open`, `Decided`, or `Revisit`. Agents must read this before any task that touches a decision here, and must never resolve an `Open` item themselves: file a blocker (`hloop blocker add`) instead.\n\n---\n")
	if len(l.Decisions) == 0 {
		b.WriteString("\n_No decisions recorded yet._\n")
	}
	for _, d := range l.Decisions {
		fmt.Fprintf(&b, "\n### %s. %s: **%s**\n", d.ID, d.Topic, d.Status)
		if d.Options != "" {
			fmt.Fprintf(&b, "- Options under consideration: %s\n", d.Options)
		}
		if d.Needs != "" {
			fmt.Fprintf(&b, "- Needs: %s\n", d.Needs)
		}
		if d.Decision != "" {
			fmt.Fprintf(&b, "- Decision: %s\n", d.Decision)
		}
		if d.Rationale != "" {
			fmt.Fprintf(&b, "- Rationale: %s\n", d.Rationale)
		}
		if d.Date != "" {
			fmt.Fprintf(&b, "- Date: %s\n", d.Date)
		}
	}
	return b.String()
}

// RenderViews writes both generated documents.
func RenderViews(p Project, l Ledger) error {
	name := "project"
	if c, err := p.LoadConfig(); err == nil && c.Name != "" {
		name = c.Name
	}
	if err := writeAtomic(p.Path("PROGRESS.md"), []byte(RenderProgress(name, l)), 0o644); err != nil {
		return err
	}
	if err := writeAtomic(p.Path("DECISIONS.md"), []byte(RenderDecisions(l)), 0o644); err != nil {
		return err
	}
	if err := writeAtomic(p.Path("LESSONS.md"), []byte(RenderLessons(l)), 0o644); err != nil {
		return err
	}
	if err := writeAtomic(p.Path("PROGRESS_LOG.md"), []byte(RenderProgressLog(name, l)), 0o644); err != nil {
		return err
	}
	// tasks.md next to every spec that lives in its own folder
	specs := map[string]bool{}
	for _, t := range l.Tasks {
		if strings.HasPrefix(t.Spec, "specs/") && strings.HasSuffix(t.Spec, "/spec.md") && ValidPromptPath(t.Spec) {
			specs[t.Spec] = true
		}
	}
	for s := range specs {
		dir := filepath.Dir(p.Path(filepath.FromSlash(s)))
		if st, err := os.Stat(dir); err != nil || !st.IsDir() {
			continue
		}
		if err := writeAtomic(filepath.Join(dir, "tasks.md"), []byte(RenderSpecTasks(s, l)), 0o644); err != nil {
			return err
		}
	}
	return nil
}
