func TestRunLockExclusiveAndStale(t *testing.T) {
	p := Project{Root: t.TempDir()}
	l1, err := p.AcquireRun()
	if err != nil {
		t.Fatal(err)
	}
	if _, err := p.AcquireRun(); err != ErrBusy {
		t.Fatalf("second acquire = %v, want ErrBusy", err)
	}
	if !p.RunActive() {
		t.Fatal("RunActive should be true")
	}
	l1.Release()
	if p.RunActive() {
		t.Fatal("lock should be gone")
	}
	// a lock left behind by a crashed run goes stale
	if err := os.WriteFile(p.runLockPath(), []byte("pid=1"), 0o600); err != nil {
		t.Fatal(err)
	}
	old := time.Now().Add(-10 * time.Minute)
	_ = os.Chtimes(p.runLockPath(), old, old)
	l2, err := p.AcquireRun()
	if err != nil {
		t.Fatalf("stale lock should be reclaimed: %v", err)
	}
	l2.Release()
}

