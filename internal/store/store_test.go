func TestBlockersAndDecisions(t *testing.T) {
	var l Ledger
	l.AddBlocker("need key", "agent")
	l.AddBlocker("need dns", "agent")
	if len(l.OpenBlockers()) != 2 {
		t.Fatal("want 2 open")
	}
	if _, err := l.ResolveBlocker("b1", "done"); err != nil {
		t.Fatal(err)
	}
	if len(l.OpenBlockers()) != 1 {
		t.Fatal("want 1 open")
	}
	if _, err := l.ResolveBlocker("all", "rest"); err != nil || len(l.OpenBlockers()) != 0 {
		t.Fatalf("resolve all: %v", err)
	}
	if _, err := l.ResolveBlocker("B9", ""); err == nil {
		t.Fatal("unknown blocker must error")
	}
	d := l.AddDecision("DB", "pg | sqlite", "scale")
	if d.Status != DecisionOpen || len(l.OpenDecisions()) != 1 {
		t.Fatal("decision should start Open")
	}
	if _, err := l.ResolveDecision("1", "pg", "team knows it"); err != nil || len(l.OpenDecisions()) != 0 {
		t.Fatalf("resolve decision: %v", err)
	}
}

