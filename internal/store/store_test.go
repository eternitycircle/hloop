func TestUpdateLedgerConcurrentAndRendered(t *testing.T) {
	p := Project{Root: t.TempDir()}
	if err := p.SaveConfig(DefaultConfig("demo", "agy")); err != nil {
		t.Fatal(err)
	}
	var wg sync.WaitGroup
	for i := 0; i < 20; i++ {
		wg.Add(1)
		go func(i int) {
			defer wg.Done()
			if err := UpdateLedger(p, func(l *Ledger) error {
				l.AddTask(fmt.Sprintf("task %d", i), "", "cli", "", false)
				return nil
			}); err != nil {
				t.Error(err)
			}
		}(i)
	}
	wg.Wait()
	l, err := LoadLedger(p)
	if err != nil {
		t.Fatal(err)
	}
	seen := map[string]bool{}
	for _, tk := range l.Tasks {
		if seen[tk.ID] {
			t.Fatalf("duplicate id %s", tk.ID)
		}
		seen[tk.ID] = true
	}
	if len(l.Tasks) != 20 {
		t.Fatalf("lost updates: %d tasks", len(l.Tasks))
	}
	md, err := os.ReadFile(p.Path("PROGRESS.md"))
	if err != nil || !strings.Contains(string(md), "GENERATED by hloop") || !strings.Contains(string(md), "Status: None") {
		t.Fatalf("rendered progress missing banner/status: %v", err)
	}
}

