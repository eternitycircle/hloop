func TestLedgerOrderingAndLifecycle(t *testing.T) {
	var l Ledger
	l.AddTask("a", "", "cli", "", false)
	l.AddTask("b", "", "cli", "", false)
	l.AddTask("c", "", "cli", "", true) // jumps ahead of a and b
	got := []string{l.Tasks[0].Title, l.Tasks[1].Title, l.Tasks[2].Title}
	if strings.Join(got, "") != "cab" {
		t.Fatalf("order = %v, want c a b", got)
	}
	cur := l.Promote()
	if cur == nil || cur.Title != "c" || cur.Status != TaskInProgress {
		t.Fatalf("promote = %+v", cur)
	}
	if again := l.Promote(); again.ID != cur.ID {
		t.Fatalf("second promote must keep the current task")
	}
	if _, err := l.Complete("", "abc", "did c"); err != nil {
		t.Fatal(err)
	}
	if _, err := l.Complete("T3", "", ""); err == nil {
		t.Fatal("completing an already done task must fail")
	}
	if l.Remaining() != 2 || l.Count(TaskDone) != 1 {
		t.Fatalf("remaining=%d done=%d", l.Remaining(), l.Count(TaskDone))
	}
	if !l.MoveToFront("T2") || l.NextPending().ID != "T2" {
		t.Fatalf("MoveToFront failed: next=%v", l.NextPending())
	}
}

