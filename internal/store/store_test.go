func TestRegistryUniqueNames(t *testing.T) {
	t.Setenv("HLOOP_HOME", t.TempDir())
	a, _ := Register("My App", "/tmp/a")
	b, _ := Register("My App", "/tmp/b")
	again, _ := Register("whatever", "/tmp/a")
	if a != "my-app" || b != "my-app-2" || again != a {
		t.Fatalf("names: %q %q %q", a, b, again)
	}
	if p, err := Lookup("my-app-2"); err != nil || p.Root != "/tmp/b" {
		t.Fatalf("lookup: %v %v", p, err)
	}
	if err := Unregister("my-app"); err != nil {
		t.Fatal(err)
	}
	if _, err := Lookup("my-app"); err == nil {
		t.Fatal("removed project still found")
	}
}

func TestConfigValidate(t *testing.T) {
	c := DefaultConfig("x", "agy")
	if probs := c.Validate(); len(probs) != 0 {
		t.Fatalf("default config invalid: %v", probs)
	}
	c.Agents["rev"] = Agent{Adapter: "agy", Role: "reviewer", Mode: "loop-only", Trigger: "every_n_turns"}
	c.Pipeline = append(c.Pipeline, "rev")
	if probs := c.Validate(); len(probs) == 0 {
		t.Fatal("every_n_turns without every_n must be rejected")
	}
	c.Agents["rev"] = Agent{Adapter: "agy", Role: "reviewer", Mode: "oops", Trigger: "manual"}
	if probs := c.Validate(); len(probs) == 0 {
		t.Fatal("bad mode must be rejected")
	}
}

